/// <summary>
/// Tests that need a P.I. Engineering (X-keys) device: inconclusive, not failed, when none is plugged in or the DLL is missing.
/// They send only Generate Data (command 177) to a device, which asks it for a report and changes nothing; no LED, unit ID or any
/// other command is ever sent. Each is tried once more when it fails, because another process may be using the same devices.
/// </summary>
[TestClass]
public sealed class HardwareTests
{
    [TestMethod]
    public void EnumerationFindsTheConsumerInterfaceOfEveryDevice()
    {
        IReadOnlyList<XkDeviceDescriptor> devices = TestSupport.RequireDevices();
        foreach (XkDeviceDescriptor d in devices)
        {
            Assert.AreEqual(0x05F3, d.Vid);
            Assert.AreEqual(0x0C, d.UsagePage);
            Assert.AreEqual(36, d.OutputLength);
            Assert.IsTrue(d.InputLength is > 0 and <= XkReportEntry.MaxDataLength, $"input length {d.InputLength}");
            StringAssert.StartsWith(d.Path, @"\\?\hid#vid_05f3", StringComparison.OrdinalIgnoreCase);
            Assert.IsFalse(string.IsNullOrWhiteSpace(d.Product));
        }
    }

    [TestMethod]
    public void EnumeratingRepeatedlyReturnsTheSameDevices()
    {
        IReadOnlyList<XkDeviceDescriptor> first = TestSupport.RequireDevices();
        for (int i = 0; i < 50; i++)
        {
            CollectionAssert.AreEquivalent(first.Select(d => d.Path).ToList(), XkEnumerator.Enumerate().Where(d => d.InputLength > 0).Select(d => d.Path).ToList());
        }
    }

    [TestMethod]
    public void GenerateDataIsAnsweredStampedAndSignaled()
    {
        IReadOnlyList<XkDeviceDescriptor> devices = TestSupport.RequireDevices();
        TestSupport.RetryOnce(() =>
        {
            foreach (XkDeviceDescriptor descriptor in devices)
            {
                using XkDevice device = XkDevice.Open(descriptor);
                Assert.AreEqual(descriptor.InputLength, device.InputLength);
                Assert.AreEqual(36, device.OutputLength);
                long before = Stopwatch.GetTimestamp();
                Assert.AreEqual(XkError.Ok, TestSupport.GenerateData(device));
                Assert.IsTrue(device.WaitHandle.WaitOne(1000), "no report within a second");
                long after = Stopwatch.GetTimestamp();
                Thread.Sleep(50);
                List<XkReportEntry> got = TestSupport.ReadAll(device);
                Assert.AreEqual(1, got.Count, "one answer and nothing else");
                XkReportEntry e = got[0];
                Assert.IsFalse(e.IsError);
                Assert.IsTrue(e.Qpc >= before && e.Qpc <= after, "the stamp is on the Stopwatch clock and falls inside the request/answer window");
                Assert.AreEqual(descriptor.InputLength, e.Length);
                Assert.AreEqual(0u, e.Sequence);
                byte[] data = new byte[XkReportEntry.MaxDataLength];
                int length = e.CopyDataTo(data);
                Assert.AreEqual(descriptor.InputLength, length);
                Assert.AreEqual(2, data[2] & 2, "data type: generated by Generate Data");
                if (XkHid.TimestampOffset(descriptor.Pid) >= 0)
                {
                    Assert.IsTrue(e.HasDeviceMs);
                }
            }
        });
    }

    [TestMethod]
    public void AFullRingDropsTheNewestAndCountsThem()
    {
        XkDeviceDescriptor descriptor = TestSupport.RequireDevices()[0];
        TestSupport.RetryOnce(() =>
        {
            using XkDevice device = XkDevice.Open(descriptor, ringCapacity: 16);
            for (int i = 0; i < 20; i++)
            {
                Assert.AreEqual(XkError.Ok, TestSupport.GenerateData(device));
            }
            Thread.Sleep(200);
            List<XkReportEntry> got = TestSupport.ReadAll(device);
            Assert.AreEqual(15, got.Count);
            Assert.AreEqual(5ul, device.DroppedCount);
            CollectionAssert.AreEqual(Enumerable.Range(0, 15).Select(i => (uint)i).ToList(), got.Select(e => e.Sequence).ToList());
            Assert.AreEqual(XkError.Ok, TestSupport.GenerateData(device));
            Thread.Sleep(100);
            List<XkReportEntry> next = TestSupport.ReadAll(device);
            Assert.AreEqual(1, next.Count);
            Assert.AreEqual(20u, next[0].Sequence, "the gap in sequence numbers shows the drops");
        });
    }

    [TestMethod]
    public void ASecondSessionOnTheSameInterfaceGetsItsOwnReports()
    {
        XkDeviceDescriptor descriptor = TestSupport.RequireDevices()[0];
        TestSupport.RetryOnce(() =>
        {
            using XkDevice a = XkDevice.Open(descriptor);
            using XkDevice b = XkDevice.Open(descriptor);
            Assert.AreEqual(XkError.Ok, TestSupport.GenerateData(a));
            Thread.Sleep(200);
            Assert.AreEqual(1, TestSupport.ReadAll(a).Count);
            Assert.AreEqual(1, TestSupport.ReadAll(b).Count);
        });
    }

    [TestMethod]
    public void AWrongLengthWriteIsRefused()
    {
        XkDeviceDescriptor descriptor = TestSupport.RequireDevices()[0];
        using XkDevice device = XkDevice.Open(descriptor);
        // An all-zero report: never a command, and refused for its length before it reaches the device.
        Assert.AreEqual(XkError.WriteLength, device.Write(new byte[35], 1000, out _));
    }

    [TestMethod]
    public void OpeningAndClosingWhileAReadIsPendingIsPromptAndRepeatable()
    {
        XkDeviceDescriptor descriptor = TestSupport.RequireDevices()[0];
        Stopwatch watch = Stopwatch.StartNew();
        for (int i = 0; i < 100; i++)
        {
            using XkDevice device = XkDevice.Open(descriptor, flags: i % 2 == 0 ? XkOpenFlags.Mmcss : 0);
        }
        Assert.IsLessThan(10_000, watch.ElapsedMilliseconds, "100 open/close cycles took too long");
    }

    [TestMethod]
    public void AClosedDeviceCannotBeUsed()
    {
        XkDeviceDescriptor descriptor = TestSupport.RequireDevices()[0];
        XkDevice device = XkDevice.Open(descriptor);
        device.Dispose();
        device.Dispose();
        _ = Assert.Throws<ObjectDisposedException>(() => TestSupport.GenerateData(device));
    }

    [TestMethod]
    public void AnUnknownPathCannotBeOpened()
    {
        TestSupport.RequireDll();
        XkDeviceDescriptor missing = new(@"\\?\hid#vid_05f3&pid_ffff&mi_00#0&0&0&0#{4d1e55b2-f16f-11cf-88cb-001111000030}", 0x05F3, 0xFFFF, 0, 0x0C, 1, 33, 36, 0, "", "");
        Assert.AreEqual(XkError.NotFound, XkDevice.TryOpen(missing, 0, 0, out XkDevice? device));
        Assert.IsNull(device);
        XkHidException ex = Assert.Throws<XkHidException>(() => XkDevice.Open(missing));
        Assert.AreEqual(XkError.NotFound, ex.Code);
    }

    /// <summary>
    /// The library's device classes on the push API, against real devices: every present device is connected when GetDevices returns, in the
    /// library's device order, and its answer to Generate Data arrives through the device's events. An unplug and a replug are simulated
    /// through the manager's monitor (its enumeration and watch generation are replaced; the sessions are real): the device goes to
    /// Disconnected with its inputs released, and the returning interface is attached to the same entry. Only Generate Data is sent: the
    /// identification LEDs, the descriptor request and every other command are turned off.
    /// </summary>
    [TestMethod]
    public void XKeysDevicesOpensReadsAndReopensTheDevices()
    {
        IReadOnlyList<XkDeviceDescriptor> present = TestSupport.RequireDevices();
        TestSupport.RetryOnce(() =>
        {
            List<XKeysDeviceSettings> settings = [];
            var devices = XKeysDevices<TestKey>.GetDevices(settings, NullLoggerFactory.Instance, new XKeysDeviceOptions(Identify: false, RequestDeviceInfo: false, RequestUpdate: true));
            XKeysDeviceManager<TestKey>? manager = devices.Select(d => d.Manager).FirstOrDefault(m => m is not null);
            try
            {
                Assert.IsNotNull(manager);
                Assert.IsGreaterThanOrEqualTo(present.Count, devices.Count);
                for (int i = 0; i < present.Count; i++)
                {
                    XKeysDevice<TestKey> device = devices[i];
                    Assert.IsTrue(device.IsConnected, $"entry {i} is connected when GetDevices returns");
                    Assert.AreEqual(present[i].Path, device.CurrentPath, ignoreCase: true, $"entry {i} is the {i}th device in the library's order");
                    Assert.AreEqual(present[i], device.Descriptor);
                    Assert.AreEqual(XkModel.ForPid(present[i].Pid), device.Model);
                    Assert.AreEqual(XkModel.ForPid(present[i].Pid).NameForPid(present[i].Pid), device.NamePrefix, "named from the catalogue");
                    Assert.AreEqual(RemoteServiceStates.Connected, device.ServiceState.AggregateState);
                    Assert.AreEqual(XkDeliveryMode.Events, device.Session!.DeliveryMode, "pushed, not polled");
                    Assert.IsTrue(SpinWait.SpinUntil(() => device.Id != 0, 2000), $"device 0x{device.Settings.Pid:X4} delivered no report");
                }

                // Simulate the victim leaving: it is no longer enumerated, and the watch has moved on.
                XkDeviceMonitor monitor = manager.Monitor;
                long generation = 1_000_000;
                List<XkDeviceDescriptor> listed = [.. present];
                monitor.EnumerateOverride = () => { lock (listed) { return [.. listed]; } };
                monitor.GenerationOverride = () => (ulong)Interlocked.Read(ref generation);
                XKeysDevice<TestKey> victim = devices[0];
                XkDevice old = victim.Session!;
                lock (listed)
                {
                    listed.RemoveAt(0);
                }
                Interlocked.Increment(ref generation);
                monitor.Rescan();
                Assert.IsTrue(SpinWait.SpinUntil(() => !victim.IsConnected, 3000), "the removal did not detach the device");
                Assert.AreEqual(XkCloseReason.Removed, old.CloseReason);
                Assert.AreEqual(RemoteServiceStates.Disconnected, victim.ServiceState.AggregateState);
                Assert.IsTrue(victim.Triggers.Values.All(t => !t.IsDown), "inputs are released");

                // And coming back: the same entry gets the new session.
                victim.Id = 0;
                lock (listed)
                {
                    listed.Insert(0, present[0]);
                }
                Interlocked.Increment(ref generation);
                monitor.Rescan();
                Assert.IsTrue(SpinWait.SpinUntil(() => victim.IsConnected, 3000), "the device was not attached again");
                Assert.AreNotSame(old, victim.Session);
                Assert.AreEqual(present[0].Path, victim.CurrentPath, ignoreCase: true);
                Assert.AreEqual(RemoteServiceStates.Connected, victim.ServiceState.AggregateState);
                Assert.IsTrue(SpinWait.SpinUntil(() => victim.Id != 0, 2000), "no report after reopening (the update request was not answered)");
            }
            finally
            {
                manager?.Dispose();
            }
            Assert.IsTrue(devices.All(d => !d.IsConnected), "disposing the manager releases every session");
        });
    }

    /// <summary>
    /// Optional long run, for the memory figures: enumerates repeatedly while reading reports and reopening a device, and checks that
    /// private bytes stay flat. Runs for the number of seconds in the XKEYS_SOAK_SECONDS environment variable; inconclusive when it is not set.
    /// </summary>
    [TestMethod]
    public void SoakEnumeratingAndReadingKeepsPrivateBytesFlat()
    {
        if (!int.TryParse(Environment.GetEnvironmentVariable("XKEYS_SOAK_SECONDS"), out int seconds) || seconds <= 0)
        {
            Assert.Inconclusive("Set XKEYS_SOAK_SECONDS to run the soak test.");
        }
        XkDeviceDescriptor descriptor = TestSupport.RequireDevices()[0];
        using Process process = Process.GetCurrentProcess();
        long Measure()
        {
            GC.Collect();
            GC.WaitForPendingFinalizers();
            GC.Collect();
            process.Refresh();
            return process.PrivateMemorySize64;
        }

        long enumerations = 0;
        long reports = 0;
        long baseline = 0;
        long last = 0;
        List<string> samples = [];
        Stopwatch watch = Stopwatch.StartNew();
        long nextSample = 0;
        long nextRequest = 0;
        long nextReopen = 0;
        XkDevice? device = null;
        try
        {
            while (watch.Elapsed.TotalSeconds < seconds)
            {
                _ = XkEnumerator.Enumerate();
                enumerations++;
                long ms = watch.ElapsedMilliseconds;
                if (ms >= nextReopen)
                {
                    device?.Dispose();
                    device = XkDevice.Open(descriptor);
                    nextReopen = ms + 5000;
                }
                if (ms >= nextRequest)
                {
                    _ = TestSupport.GenerateData(device!);
                    nextRequest = ms + 100;
                }
                reports += TestSupport.ReadAll(device!).Count;
                if (ms >= nextSample)
                {
                    last = Measure();
                    if (baseline == 0 && ms >= 10_000)
                    {
                        baseline = last;
                    }
                    samples.Add($"{ms / 1000,4} s  private {last:N0}  enumerations {enumerations:N0}  reports {reports:N0}  handles {process.HandleCount}");
                    nextSample = ms + 10_000;
                }
                Thread.Sleep(5);
            }
            last = Measure();
        }
        finally
        {
            device?.Dispose();
        }
        samples.Add($"end   private {last:N0}  enumerations {enumerations:N0}  reports {reports:N0}");
        TestContext.WriteLine(string.Join(Environment.NewLine, samples));
        Console.WriteLine(string.Join(Environment.NewLine, samples));
        Assert.IsGreaterThan(0L, reports);
        if (baseline != 0)
        {
            Assert.IsLessThan(2L * 1024 * 1024, last - baseline, $"private bytes grew from {baseline:N0} to {last:N0}");
        }
    }

    public TestContext TestContext { get; set; } = null!;

    [TestMethod]
    public async Task TheAsyncWaitCompletesWhenAReportArrivesAndCanBeCanceled()
    {
        XkDeviceDescriptor descriptor = TestSupport.RequireDevices()[0];
        using XkDevice device = XkDevice.Open(descriptor);
        using (CancellationTokenSource cts = new(100))
        {
            Assert.IsFalse(await device.WaitAsync(cts.Token), "nothing was requested, so canceled");
        }
        Assert.AreEqual(XkError.Ok, TestSupport.GenerateData(device));
        using CancellationTokenSource timeout = new(2000);
        Assert.IsTrue(await device.WaitAsync(timeout.Token), "no report within 2 s");
        Assert.IsGreaterThan(0, TestSupport.ReadAll(device).Count);
    }
